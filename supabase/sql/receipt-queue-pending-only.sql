-- Only pending, undelivered orders belong to the receipt waiting queue.
create or replace view public.gazi_order_list with (security_invoker=true) as
 SELECT siparis_no,
    siparis_tel,
    ad_soyad,
    musteri_tel,
    adres,
    urun_bilgisi,
    sehir,
    toplam_tutar,
    odeme_sekli,
    notlar,
    tarih,
    musteri_no,
    firma,
    siparis_alan,
    ilce,
    kargo_durumu,
    orderinvoiceid,
    orderinvoicedetailid,
    shipperbranchcode,
    kargo_adet,
    sehir_kodu,
    ilce_kodu,
    kargo_siparis_no,
    kargo_takip_kodu,
    kargo_qr_kod,
    invoiceid,
    kargo_kg,
    zpl_base64,
    print,
    iptal_nedeni,
    iptal_tarihi,
    "shipmentStatus",
    kargo_takip_url,
    kargo_gunc_saat,
    teslimat_aciklama,
    gonder_hata_bilgisi,
    "shipmentStatusCode",
    secilen_urunler,
    "isDelivered",
    kargo_api_yanit,
    kargo_zpl,
    iade_kodu,
    iade_etiket_url,
    iade_durumu,
    iade_tarihi,
    subeden_teslim,
    teslim_subesi,
    teslim_sekli_kontrol,
    etiket_yazdirma_sayisi,
    etiket_son_yazdirma,
    etiket_olusturma_tarihi,
    sube_etiket_durumu,
    sube_etiket_tarihi,
    bolunme_grubu,
    bolunme_ana_siparis_no,
    bolunme_sira,
    liste_sira_no,
    liste_etiket_tarihi,
    iade_takip_kodu,
    iade_teslim_tarihi,
    iade_tamamlandi,
    NOT COALESCE(tarih < '2026-10-15 00:00:00'::timestamp without time zone AND (odeme_sekli ~* '\m(eft|iban|havale|fast|bedelsiz|ücretsiz|ucretsiz)\M'::text OR toplam_tutar ~* '^[[:space:]]*[+-]?0+([.,]0+)*[[:space:]]*(TL|TRY|₺)?[[:space:]]*$'::text), false) AND (COALESCE(kargo_durumu, ''::text) <> ALL (ARRAY['Silindi'::text, 'İptal'::text])) AND (concat_ws(' '::text, odeme_sekli, notlar) ~* '\m(eft|iban|havale|fast)\M'::text AND NOT (EXISTS ( SELECT 1
           FROM order_receipts r
          WHERE r.order_id = v.siparis_no)) OR (EXISTS ( SELECT 1
           FROM order_receipts r
          WHERE r.order_id = v.siparis_no AND (r.status = ANY (ARRAY['pending'::text, 'rejected'::text]))))) AND coalesce(v.kargo_durumu,'') = 'Bekliyor' AND v."isDelivered" IS NOT TRUE AND v."shipmentStatusCode" IS DISTINCT FROM 5 AND coalesce(v."shipmentStatus",'') NOT IN ('Teslim_Edildi','Teslim Edildi') AS dekont_bekliyor,
    COALESCE(tarih < '2026-10-15 00:00:00'::timestamp without time zone AND (odeme_sekli ~* '\m(eft|iban|havale|fast|bedelsiz|ücretsiz|ucretsiz)\M'::text OR toplam_tutar ~* '^[[:space:]]*[+-]?0+([.,]0+)*[[:space:]]*(TL|TRY|₺)?[[:space:]]*$'::text), false) AS dekont_gecmis_onayli
   FROM ( SELECT o.siparis_no,
            o.siparis_tel,
            o.ad_soyad,
            o.musteri_tel,
            o.adres,
            o.urun_bilgisi,
            o.sehir,
            o.toplam_tutar,
            o.odeme_sekli,
            o.notlar,
            o.tarih,
            o.musteri_no,
            o.firma,
            o.siparis_alan,
            o.ilce,
            o.kargo_durumu,
            o.orderinvoiceid,
            o.orderinvoicedetailid,
            o.shipperbranchcode,
            o.kargo_adet,
            o.sehir_kodu,
            o.ilce_kodu,
            o.kargo_siparis_no,
            o.kargo_takip_kodu,
            o.kargo_qr_kod,
            o.invoiceid,
            o.kargo_kg,
            "left"(o.zpl_base64, 5) AS zpl_base64,
            o.print,
            o.iptal_nedeni,
            o.iptal_tarihi,
            o."shipmentStatus",
            o.kargo_takip_url,
            o.kargo_gunc_saat,
            o.teslimat_aciklama,
            o.gonder_hata_bilgisi,
            o."shipmentStatusCode",
            o.secilen_urunler,
            o."isDelivered",
                CASE
                    WHEN o.kargo_api_yanit IS JSON OBJECT THEN jsonb_build_object('environment', o.kargo_api_yanit::jsonb -> 'environment'::text, 'tracking', o.kargo_api_yanit::jsonb -> 'tracking'::text)::text
                    ELSE o.kargo_api_yanit
                END AS kargo_api_yanit,
                CASE
                    WHEN o.kargo_zpl IS NULL OR btrim(o.kargo_zpl) = ''::text THEN o.kargo_zpl
                    ELSE '[stored]'::text
                END AS kargo_zpl,
            o.iade_kodu,
            o.iade_etiket_url,
            o.iade_durumu,
            o.iade_tarihi,
            o.subeden_teslim,
            o.teslim_subesi,
            o.teslim_sekli_kontrol,
            o.etiket_yazdirma_sayisi,
            o.etiket_son_yazdirma,
            o.etiket_olusturma_tarihi,
            o.sube_etiket_durumu,
            o.sube_etiket_tarihi,
            o.bolunme_grubu,
            o.bolunme_ana_siparis_no,
            o.bolunme_sira,
            COALESCE(o.bolunme_ana_siparis_no, o.siparis_no) AS liste_sira_no,
            groups.group_label_created AS liste_etiket_tarihi,
            o.iade_takip_kodu,
            o.iade_teslim_tarihi,
            o.iade_teslim_tarihi IS NOT NULL AS iade_tamamlandi
           FROM gazi_siparisler o
             LEFT JOIN ( SELECT COALESCE(gazi_siparisler.bolunme_ana_siparis_no, gazi_siparisler.siparis_no) AS group_order_id,
                    max(gazi_siparisler.etiket_olusturma_tarihi) AS group_label_created
                   FROM gazi_siparisler
                  GROUP BY (COALESCE(gazi_siparisler.bolunme_ana_siparis_no, gazi_siparisler.siparis_no))) groups ON groups.group_order_id = COALESCE(o.bolunme_ana_siparis_no, o.siparis_no)) v;
notify pgrst,'reload schema';
